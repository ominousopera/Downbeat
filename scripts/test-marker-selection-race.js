"use strict";
// Place before the next selection poll must not modify a different source.
const fs=require("fs"),path=require("path"),os=require("os"),assert=require("assert");
const root=process.env.DOWNBEAT_ROOT || path.resolve(__dirname,".."),tmp=fs.mkdtempSync(path.join(os.tmpdir(),"downbeat-place-race-"));
const media=path.join(tmp,"source.wav"),target=path.join(tmp,"target.wav");
fs.writeFileSync(media,"source");fs.writeFileSync(target,"target");
fs.mkdirSync(path.join(tmp,"Downbeat"));fs.writeFileSync(path.join(tmp,"Downbeat/settings.json"),JSON.stringify({language:"en",onboardingCompleted:true}));
const mocks=require("./host-mocks.js"),fake=mocks.makePremiereHost({mediaPath:media,durationSec:8,clipStart:10});
const clip=fake.audioTrack.clips[0],sourceMarkers=clip.projectItem.getMarkers(),targetMarkers=new sourceMarkers.constructor();
targetMarkers.createMarker(1).name="D";
const host=mocks.loadHost(fake.context);
const panel=require("./panel-harness.js").bootPanel({docsDir:tmp,realTimeouts:true,evalScript:host.evalScript});
const $=panel.registry,wait=()=>new Promise(r=>setTimeout(r,30));
(async()=>{
  $.manualBpmInput.value="120";$.manualBpmBtn._fire("click");await wait();
  assert.strictEqual(window.BeatMarkerLibrary.get(media).bpm,120);
  $.placeMarkersBtn._fire("click");await wait();
  assert.ok(sourceMarkers.numMarkers > 0);
  const placed = sourceMarkers.numMarkers;
  let mutations=0; const create=sourceMarkers.createMarker;
  sourceMarkers.createMarker=function(t){mutations++;return create.call(this,t);};
  fs.writeFileSync(media,"replaced audio with a different identity");
  $.placeMarkersBtn._fire("click");await wait();
  assert.strictEqual(sourceMarkers.numMarkers,placed);
  assert.strictEqual(mutations,0);
  sourceMarkers.list.splice(0);
  clip.projectItem={name:"target.wav",getMediaPath:()=>target,getMarkers:()=>targetMarkers};clip.name="target.wav";
  $.placeMarkersBtn._fire("click");await wait();
  assert.strictEqual(sourceMarkers.numMarkers,0);assert.strictEqual(targetMarkers.numMarkers,1);
  assert.strictEqual(targetMarkers.list[0].start.seconds,1);
  console.log("PASS stale source placement refuses to modify the newly selected clip",JSON.stringify({source:sourceMarkers.numMarkers,target:targetMarkers.list.map(m=>m.start.seconds)}));
  fs.rmSync(tmp,{recursive:true,force:true});process.exit(0);
})().catch(e=>{console.error(e);process.exit(1);});
