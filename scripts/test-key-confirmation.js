"use strict";
// Confirmed metadata must preserve detector results and beat-grid timing.
const assert = require("assert"), fs = require("fs"), os = require("os"), path = require("path");
const ROOT = process.env.DOWNBEAT_ROOT || path.join(__dirname, "..");
const dir = fs.mkdtempSync(path.join(os.tmpdir(), "downbeat-confirm-"));
const media = path.join(dir, "audio.wav");
global.window = { cep_node: { require } };
["camelot", "library", "sound-library", "analysis-cache"].forEach(function (f) { require(path.join(ROOT, "js", f + ".js")); });
const L = window.BeatMarkerLibrary, S = window.BeatMarkerSoundLibrary, A = window.BeatMarkerAnalysisCache;
const key = function (code, scope) { return Object.assign({ camelot: code, strength: 0.5, material: "music", scopeKey: scope }, window.BeatMarkerCamelot.fromCamelotCode(code)); };
try {
  fs.writeFileSync(media, "audio fixture");
  L.upsertAnalysis(media, "fixture", { bpm: 100, beatsArray: [0, 0.6, 1.2], phase: 0 });
  L.upsertKey(media, "fixture", key("8A", "music"));
  const scope = A.scopeKey("clip", "music", { inPointSeconds: 1, outPointSeconds: 3 }, 44100);
  L.upsertKey(media, "fixture", key("10A", scope));
  assert.strictEqual(L.getKey(media, "music").camelot, "8A");
  assert.strictEqual(L.getKey(media, scope).camelot, "10A");
  assert.strictEqual(L.getKey(media, "music:44100:176400"), null);
  L.confirmKey(media, "fixture", "12B", scope);
  L.confirmBpm(media, "fixture", 128);
  assert.strictEqual(L.get(media).bpm, 100);
  assert.deepStrictEqual(L.get(media).beatsArray, [0, 0.6, 1.2]);
  assert.strictEqual(L.getKey(media, scope).manual, true);
  L.loadEntries(JSON.parse(JSON.stringify(L.getAll())));
  assert.strictEqual(L.getKey(media, scope).camelot, "12B");
  assert.strictEqual(L.get(media).confirmedBpm.value, 128);
  L.upsertKey(media, "fixture", key("11A", scope));
  assert.strictEqual(L.getKey(media, scope).camelot, "12B", "reanalysis retains confirmation");
  L.clearConfirmedKey(media, scope);
  assert.strictEqual(L.getKey(media, scope).camelot, "11A", "reset restores latest detector answer");
  assert.strictEqual(L.getKey(media, "music").camelot, "8A", "interval never overwrites full-file result");
  S.addFolder("music", dir);
  S.syncFiles("music", S.listAudioFiles(fs, "music"), []);
  S.setResult(media, Object.assign({ ok: true, bpm: 100, durationSec: 4 }, key("8A")));
  const unconfirmed = JSON.stringify(S.getState());
  S.confirm(media, "", null);
  assert.strictEqual(JSON.stringify(S.getState()), unconfirmed, "empty confirmation is a no-op");
  S.confirm(media, "10B", 128);
  assert.strictEqual(S.getState().files[media].detected.bpm, 100);
  S.loadState(JSON.parse(JSON.stringify(S.getState())));
  assert.strictEqual(S.getState().files[media].bpm, 128);
  assert.strictEqual(S.getState().files[media].keyFrom, "user");
  S.applyNameTags(media);
  assert.strictEqual(S.getState().files[media].bpm, 128, "name processing retains manual metadata");
  const before = JSON.stringify(S.getState());
  assert.throws(function () { S.confirm(media, "9A", NaN); });
  assert.strictEqual(JSON.stringify(S.getState()), before, "invalid confirmation must be atomic");
  S.setResult(media, Object.assign({ ok: true, bpm: 110, durationSec: 4 }, key("7A")));
  assert.strictEqual(S.getState().files[media].bpm, 128);
  S.clearConfirmed(media);
  assert.strictEqual(S.getState().files[media].bpm, 110);
  assert.strictEqual(S.getState().files[media].camelot, "7A");
  S.confirm(media, "10B", 128);
  fs.writeFileSync(media, "replacement audio fixture changed");
  S.syncFiles("music", S.listAudioFiles(fs, "music"), []);
  assert.strictEqual(S.getState().files[media].confirmedKey, null);
  assert.strictEqual(S.getState().files[media].status, "pending");
  assert.strictEqual(L.get(media), null);
  const clipped = A.interval(new Float32Array([0,1,2,3]), 2, { inPointSeconds: 1, outPointSeconds: 10 });
  assert.deepStrictEqual(Array.from(clipped.samples), [2,3], "end is clamped to source duration");
  assert.throws(function () { A.interval(new Float32Array(2), 2, { inPointSeconds: 5, outPointSeconds: 6 }); });
  console.log("PASS: scoped keys, confirmation persistence/reset, atomic validation, grid preservation and changed-file reset.");
} finally { fs.rmSync(dir, { recursive: true, force: true }); }
