"use strict";
// Builds js/ucs-data.js from the Universal Category System list. UCS is a
// public-domain naming standard for sound effects
// (universalcategorysystem.com): a file name starts with a CatID such as
// "DSGNWhsh" (DESIGNED / WHOOSH). The list also carries English synonyms per
// category and translations (19 languages, Russian and Spanish among them),
// which make up the Library search's thesaurus. Only the list's CSV is read.
// Output: js/ucs-data.js - window.BeatMarkerUcsData = { version, list }, one
// row per CatID: [catId, category, subCategory, synonymsEn, categoryRu,
// subCategoryRu, synonymsRu, categoryEs, subCategoryEs, synonymsEs]. Synonyms
// are lower-cased and de-duplicated; explanations are left out.
// Run: node scripts/build-ucs-data.js [path/to/_categorylist.csv]
const fs = require("fs");
const path = require("path");
const crypto = require("crypto");

const EXPECTED_SHA256 = "2bda398cd3d524201cb67d1cb09a21cdb00e52ff2ae5e6c46f1c47461735c620";
const UCS_VERSION = "8.2.1";
const input = process.argv[2];
if (!input) {
  console.error("usage: node scripts/build-ucs-data.js <path/to/_categorylist.csv>");
  process.exit(1);
}
const output = path.join(__dirname, "..", "js", "ucs-data.js");

const raw = fs.readFileSync(input);
const sha = crypto.createHash("sha256").update(raw).digest("hex");
if (sha !== EXPECTED_SHA256) {
  console.error("refusing: " + input + " has sha256 " + sha + ", expected " + EXPECTED_SHA256 + " (UCS " + UCS_VERSION + ")");
  process.exit(1);
}
// RFC 4180 CSV: quoted fields may hold commas, quotes ("") and newlines.
function parseCsv(text) {
  const rows = [];
  let row = [], field = "", quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === "\"") {
        if (text[i + 1] === "\"") { field += "\""; i++; } else { quoted = false; }
      } else {
        field += c;
      }
    } else if (c === "\"") {
      quoted = true;
    } else if (c === ",") {
      row.push(field); field = "";
    } else if (c === "\n" || c === "\r") {
      if (c === "\r" && text[i + 1] === "\n") { i++; }
      row.push(field); field = "";
      rows.push(row); row = [];
    } else {
      field += c;
    }
  }
  if (field !== "" || row.length) { row.push(field); rows.push(row); }
  return rows.filter(function (r) { return r.length > 1; });
}

const rows = parseCsv(raw.toString("utf8").replace(/^﻿/, ""));
const header = rows[0];
const col = function (name) {
  const i = header.indexOf(name);
  if (i === -1) { throw new Error("column missing: " + name); }
  return i;
};
const C = {
  cat: col("Category"), sub: col("SubCategory"), id: col("CatID"), syn: col("Synonyms - Comma Separated"),
  catRu: col("Category_ru"), subRu: col("SubCategory_ru"), synRu: col("Synonyms_ru"),
  catEs: col("Category_es"), subEs: col("SubCategory_es"), synEs: col("Synonyms_es")
};
function synonyms(text) {
  const seen = {};
  return String(text || "").split(",").map(function (s) { return s.trim().toLowerCase(); })
    .filter(function (s) { if (!s || seen[s]) { return false; } seen[s] = true; return true; }).join(",");
}
const list = rows.slice(1).map(function (r) {
  return [r[C.id].trim(), r[C.cat].trim(), r[C.sub].trim(), synonyms(r[C.syn]),
          r[C.catRu].trim(), r[C.subRu].trim(), synonyms(r[C.synRu]),
          r[C.catEs].trim(), r[C.subEs].trim(), synonyms(r[C.synEs])];
}).filter(function (r) { return /^[A-Za-z0-9]+$/.test(r[0]); });

const body = "// GENERATED by scripts/build-ucs-data.js from the Universal Category System\n" +
  "// " + UCS_VERSION + " list (public domain, universalcategorysystem.com; source sha256\n" +
  "// " + EXPECTED_SHA256 + "). Do not edit by hand - see NOTICE.md.\n" +
  "(function (global) {\n  \"use strict\";\n  global.BeatMarkerUcsData = {\n    version: \"" + UCS_VERSION + "\",\n" +
  "    // [catId, category, subCategory, synonymsEn, categoryRu, subCategoryRu, synonymsRu, categoryEs, subCategoryEs, synonymsEs]\n" +
  "    list: [\n" + list.map(function (r) { return "      " + JSON.stringify(r); }).join(",\n") + "\n    ]\n  };\n" +
  "})(typeof window !== \"undefined\" ? window : globalThis);\n";
fs.writeFileSync(output, body);
console.log("wrote " + output + ": " + list.length + " categories, " + (body.length / 1024).toFixed(0) + " KB");
