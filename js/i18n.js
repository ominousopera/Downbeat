  var currentLanguage = "en";

  function getLanguage() {
    return currentLanguage;
  }

  function setLanguage(lang) {
    if (LANGUAGES.indexOf(lang) === -1) {
      return;
    }
    currentLanguage = lang;
  }
  // Falls back to English, then to the raw key itself, so a missing
  // translation shows up as a visible key rather than blank text.
  function t(key, vars) {
    var dict = STRINGS[currentLanguage] || STRINGS.en;
    var text = dict[key];
    if (text === undefined) {
      text = STRINGS.en[key];
    }
    if (text === undefined) {
      text = key;
    }
    if (vars) {
      for (var k in vars) {
        if (vars.hasOwnProperty(k)) {
          text = text.split("{" + k + "}").join(String(vars[k]));
        }
      }
    }
    return text;
  }
  // Applies every data-i18n* attribute currently in the DOM: data-i18n
  // (textContent), data-i18n-placeholder and data-i18n-title.
  function applyStaticTranslations(root) {
    var scope = root || document;
    var textNodes = scope.querySelectorAll("[data-i18n]");
    for (var i = 0; i < textNodes.length; i++) {
      textNodes[i].textContent = t(textNodes[i].getAttribute("data-i18n"));
    }
    var placeholderNodes = scope.querySelectorAll("[data-i18n-placeholder]");
    for (var j = 0; j < placeholderNodes.length; j++) {
      placeholderNodes[j].placeholder = t(placeholderNodes[j].getAttribute("data-i18n-placeholder"));
    }
    var titleNodes = scope.querySelectorAll("[data-i18n-title]");
    for (var k = 0; k < titleNodes.length; k++) {
      titleNodes[k].title = t(titleNodes[k].getAttribute("data-i18n-title"));
    }
  }

  global.BeatMarkerI18n = {
    LANGUAGES: LANGUAGES,
    LANGUAGE_NAMES: LANGUAGE_NAMES,
    getLanguage: getLanguage,
    setLanguage: setLanguage,
    t: t,
    applyStaticTranslations: applyStaticTranslations
  };
